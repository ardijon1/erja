async function main() {
  console.log("Seeding FAQ items...");

  for (const item of FAQ_ITEMS) {
    await prisma.faqItem.upsert({
      where: { id: `faq-${item.order}` },
      update: item,
      create: { id: `faq-${item.order}`, ...item },
    });
    console.log(`  ✓ ${item.question.slice(0, 50)}...`);
  }

  console.log(`\nDone! ${FAQ_ITEMS.length} FAQ items seeded.`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
